// Builds lyrics.js (song list + lyrics) from the files in the lyrics/ folder.
//
//   lyrics/<bg>/<Song Title>.txt      e.g. lyrics/ayyappa/Kondala Kondala.txt
//
// <bg> is the category's "bg" value in songs.js. songs.js gives the categories and the
// preferred order of songs; any .txt file in a category folder that isn't listed in songs.js
// yet (e.g. a song added through the website) is added at the end of that category.
//
// Run locally:  node build.mjs        (Vercel runs it automatically on every deploy)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const CATEGORIES = new Function(fs.readFileSync(path.join(root, "songs.js"), "utf8") + "; return CATEGORIES;")();

const LYRICS = {}, INDEX = [];
let count = 0;
for (const c of CATEGORIES) {
  const dir = path.join(root, "lyrics", c.bg);
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter(f => f.toLowerCase().endsWith(".txt")) : [];
  const byTitle = new Map(files.map(f => [f.slice(0, -4).normalize("NFC"), f]));
  const listed = c.songs.map(s => s.title.normalize("NFC")).filter(t => byTitle.has(t));
  const extra = [...byTitle.keys()].filter(t => !listed.includes(t)).sort((a, b) => a.localeCompare(b));
  const titles = [...listed, ...extra];
  for (const t of titles) {
    const text = fs.readFileSync(path.join(dir, byTitle.get(t)), "utf8").replace(/^﻿/, "");
    if (text.trim()) LYRICS[t] = text;
  }
  INDEX.push({ name: c.name, bg: c.bg, songs: titles });
  count += titles.length;
}

const out = "// Generated by build.mjs from songs.js and the lyrics/ folder. Do not edit by hand.\n" +
  "window.LYRICS = " + JSON.stringify(LYRICS, null, 1) + ";\n" +
  "window.SONG_INDEX = " + JSON.stringify(INDEX, null, 1) + ";\n";
fs.writeFileSync(path.join(root, "lyrics.js"), out, "utf8");
console.log(`lyrics.js built: ${count} song(s) in ${INDEX.length} categories.`);
